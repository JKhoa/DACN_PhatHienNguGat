# DACN PhatHienNguGat - 2026
"""Chuẩn bị dataset train YOLO11 detection cho lớp học.

Pipeline:
1. Giải nén ``SCB_BowTurnHead_20250509.zip`` vào ``datasets/bow_turn_head/``.
   Dataset có 2 class: ``0 = BowHead`` (cúi đầu — proxy cho drowsy),
   ``1 = TurnHead`` (quay đầu — proxy cho distracted).
2. Sinh file ``data.yaml`` chuẩn Ultralytics.
3. (Optional) Chuẩn bị khung cho ``data_raw/`` — thư mục images/ và
   labels/ rỗng để bạn label bằng Roboflow/LabelImg sau.

Chạy 1 lần:
    python prepare_dataset.py
"""
from __future__ import annotations

import shutil
import zipfile
from pathlib import Path

BACKEND_ROOT: Path = Path(__file__).resolve().parent.parent
DATASETS_DIR: Path = BACKEND_ROOT / "datasets"
BOW_ZIP: Path = Path(
    r"D:/Study/DoAnChuyenNganh/DACN_PhatHienNguGat/DatabaseFull/"
    r"SCB-Dataset/SCB_BowTurnHead_20250509/SCB_BowTurnHead_20250509.zip"
)
DATA_RAW: Path = Path(
    r"D:/Study/DoAnChuyenNganh/DACN_PhatHienNguGat/data_raw"
)

BOW_OUT: Path = DATASETS_DIR / "bow_turn_head"
RAW_OUT: Path = DATASETS_DIR / "data_raw_to_label"


def extract_bow_turn_head() -> Path:
    """Giải nén zip BowTurnHead và flatten về layout YOLO chuẩn."""
    if BOW_OUT.exists() and any(BOW_OUT.rglob("*.jpg")):
        print(f"[skip] {BOW_OUT} đã tồn tại, bỏ qua giải nén")
        return BOW_OUT

    BOW_OUT.mkdir(parents=True, exist_ok=True)
    print(f"[extract] {BOW_ZIP} -> {BOW_OUT}")
    with zipfile.ZipFile(BOW_ZIP) as z:
        z.extractall(BOW_OUT)

    inner = BOW_OUT / "SCB_BowTurnHead_20250509" / "SCB5-Turn-Bow-Head-2024-9-17"
    if not inner.exists():
        raise RuntimeError(f"Không thấy cấu trúc mong đợi trong {BOW_OUT}")

    for sub in ("images", "labels"):
        src = inner / sub
        dst = BOW_OUT / sub
        if dst.exists():
            shutil.rmtree(dst)
        shutil.move(str(src), str(dst))

    shutil.rmtree(BOW_OUT / "SCB_BowTurnHead_20250509", ignore_errors=True)
    return BOW_OUT


def write_data_yaml(dataset_root: Path) -> Path:
    """Viết data.yaml cho Ultralytics train."""
    yaml_path = dataset_root / "data.yaml"
    yaml_path.write_text(
        "# Auto-generated by training/prepare_dataset.py\n"
        f"path: {dataset_root.as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "\n"
        "nc: 2\n"
        "names:\n"
        "  0: drowsy     # BowHead — học sinh cúi đầu xuống bàn\n"
        "  1: distracted # TurnHead — học sinh quay đầu mất tập trung\n",
        encoding="utf-8",
    )
    print(f"[yaml] {yaml_path}")
    return yaml_path


def scaffold_raw_labeling() -> Path:
    """Chuẩn bị thư mục cho bạn label data_raw sau (Roboflow/LabelImg)."""
    if RAW_OUT.exists() and any(RAW_OUT.rglob("*.jpg")):
        print(f"[skip] {RAW_OUT} đã có ảnh, bỏ qua")
        return RAW_OUT

    (RAW_OUT / "images").mkdir(parents=True, exist_ok=True)
    (RAW_OUT / "labels").mkdir(parents=True, exist_ok=True)

    if DATA_RAW.exists():
        count = 0
        for src in DATA_RAW.iterdir():
            if src.suffix.lower() in {".jpg", ".jpeg", ".png"}:
                dst = RAW_OUT / "images" / src.name
                if not dst.exists():
                    shutil.copy2(src, dst)
                    count += 1
        print(f"[copy] {count} ảnh -> {RAW_OUT / 'images'}")

    readme = RAW_OUT / "README.md"
    readme.write_text(
        "# data_raw → cần label\n\n"
        "Copy ảnh từ `D:/Study/DoAnChuyenNganh/DACN_PhatHienNguGat/data_raw/`.\n"
        "Label bằng:\n"
        "- **Roboflow** (recommended): upload folder `images/`, label với 2 class\n"
        "  `drowsy` và `phone_usage`, export YOLO format, paste `labels/` vào đây.\n"
        "- **LabelImg** offline: `pip install labelImg && labelImg images/ labels/`.\n\n"
        "Sau khi label xong, chạy `merge_datasets.py` (sẽ tạo sau) để gộp\n"
        "với `bow_turn_head/` thành dataset train cuối cùng.\n",
        encoding="utf-8",
    )
    return RAW_OUT


def main() -> None:
    DATASETS_DIR.mkdir(exist_ok=True)
    root = extract_bow_turn_head()
    print(f"[ok] bow_turn_head ready: {root}")
    for split in ("train", "val"):
        imgs = list((root / "images" / split).glob("*.jpg")) if (root / "images" / split).exists() else []
        print(f"     {split}: {len(imgs)} images")
    write_data_yaml(root)
    scaffold_raw_labeling()
    print("\nDone. Tiếp theo: `python train_drowsy.py`")


if __name__ == "__main__":
    main()
